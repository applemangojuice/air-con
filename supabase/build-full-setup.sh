#!/usr/bin/env bash
# Builds supabase/full-setup.sql: the original site's migrations (0001 to
# 0009, made safe to re-run) followed by pilot-upgrade.sql, in one file to
# paste into the Supabase SQL editor once. It works on an empty database, a
# partly set-up one, and one that already has everything: each step skips
# what is already there.
#
#   bash supabase/build-full-setup.sh          # rewrite full-setup.sql
#   bash supabase/build-full-setup.sh --check  # exit 1 if it's out of date

set -euo pipefail
export LC_ALL=C

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$HERE/full-setup.sql"

build() {
  cat <<'HDR'
-- Dang, It's Hot: full database setup, in one paste.
--
-- GENERATED by supabase/build-full-setup.sh: don't edit by hand.
--
-- Paste the whole file into Supabase -> SQL Editor -> New query -> Run.
-- Part 1 is the original site's tables (migrations 0001 to 0009), each step
-- skipped if it's already there. Part 2 is supabase/pilot-upgrade.sql.
-- Safe to run more than once; it never deletes anything. Afterwards run
-- supabase/check-schema.sql: it should say "All present".

begin;
HDR
  for f in "$HERE"/migrations/000*.sql; do
    printf '\n-- ===== %s (made safe to re-run) =====\n\n' "$(basename "$f")"
    sed -E \
      -e 's/create table public\./create table if not exists public./I' \
      -e '/if not exists/I! s/create index /create index if not exists /I' \
      -e '/if not exists/I! s/add column /add column if not exists /I' \
      "$f"
  done
  printf '\ncommit;\n\n-- ===== Part 2: supabase/pilot-upgrade.sql =====\n\n'
  cat "$HERE/pilot-upgrade.sql"
}

if [[ "${1:-}" == "--check" ]]; then
  if diff -q <(build) "$OUT" >/dev/null 2>&1; then echo "full-setup.sql is current"; else echo "full-setup.sql is out of date: run bash supabase/build-full-setup.sh" >&2; exit 1; fi
else
  build > "$OUT"; echo "wrote $OUT"
fi
